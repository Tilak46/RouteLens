const getPathParamsFromUrl = (urlStr: string): string[] => {
  if (!urlStr) return [];
  try {
    const pathPart = urlStr.replace(/^https?:\/\/[^\/]+/, "");
    const segments = pathPart.split("/");
    const params: string[] = [];
    segments.forEach((seg) => {
      if (seg.startsWith(":") && seg.length > 1) {
        const paramName = seg.slice(1).split("?")[0].replace(/[^a-zA-Z0-9_-]/g, "");
        if (paramName && !params.includes(paramName)) {
          params.push(paramName);
        }
      }
    });
    return params;
  } catch (e) {
    return [];
  }
};

const stripJsonComments = (jsonString: string): string => {
  if (!jsonString) return "";
  return jsonString.replace(/("([^"\\]|\\.)*")|(\/\/.*|\/\*[\s\S]*?\*\/)/g, (m, g1) => {
    if (g1) return g1;
    return "";
  });
};

const newRow = (): ApiKeyValueRow => ({
  id: `${Date.now()}_${Math.random().toString(36).slice(2)}`,
  enabled: true,
  key: "",
  value: "",
  description: "",
});

const normalizeRows = (currentRows: ApiKeyValueRow[]): ApiKeyValueRow[] => {
  const nonLastEmpty = currentRows.filter((r, idx) => {
    const isLast = idx === currentRows.length - 1;
    const hasContent = (r.key || "").trim() !== "" || (r.value || "").trim() !== "" || (r.description || "").trim() !== "";
    return hasContent || isLast;
  });

  if (nonLastEmpty.length === 0) {
    return [newRow()];
  }

  const lastItem = nonLastEmpty[nonLastEmpty.length - 1];
  if ((lastItem.key || "").trim() !== "" || (lastItem.value || "").trim() !== "" || (lastItem.description || "").trim() !== "") {
    nonLastEmpty.push(newRow());
  }

  return nonLastEmpty;
};

const getAutoGeneratedHeaders = (
  url: string,
  bodyMode: string,
  bodyText: string,
  formFields: ApiKeyValueRow[],
  auth: ApiAuth
): Array<{ key: string; value: string; description: string }> => {
  const list: Array<{ key: string; value: string; description: string }> = [];

  // 1. Host
  let hostValue = "<calculated when request is sent>";
  try {
    if (url.trim()) {
      const urlWithProto = url.match(/^https?:\/\//i) ? url : `http://${url}`;
      const parsed = new URL(urlWithProto);
      if (parsed.host) {
        hostValue = parsed.host;
      }
    }
  } catch (e) {
    // Ignore URL parse error
  }
  list.push({ key: "Host", value: hostValue, description: "The Host header specifies the host and port number of the server to which the request is being sent." });

  // 2. User-Agent
  list.push({ key: "User-Agent", value: "RouteLensRuntime/1.0.0", description: "Identifies the client software making the request." });

  // 3. Accept
  list.push({ key: "Accept", value: "*/*", description: "Specifies media types that are acceptable for the response." });

  // 4. Accept-Encoding
  list.push({ key: "Accept-Encoding", value: "gzip, deflate, br", description: "Specifies the compression algorithms acceptable for the response." });

  // 5. Connection
  list.push({ key: "Connection", value: "keep-alive", description: "Controls whether the network connection stays open after the transaction finishes." });

  // 6. Content-Type
  if (bodyMode === "json") {
    list.push({ key: "Content-Type", value: "application/json", description: "The format of the payload in the request body." });
  } else if (bodyMode === "text") {
    list.push({ key: "Content-Type", value: "text/plain", description: "The format of the payload in the request body." });
  } else if (bodyMode === "javascript") {
    list.push({ key: "Content-Type", value: "application/javascript", description: "The format of the payload in the request body." });
  } else if (bodyMode === "html") {
    list.push({ key: "Content-Type", value: "text/html", description: "The format of the payload in the request body." });
  } else if (bodyMode === "xml") {
    list.push({ key: "Content-Type", value: "application/xml", description: "The format of the payload in the request body." });
  } else if (bodyMode === "urlencoded" || bodyMode === "form") {
    list.push({ key: "Content-Type", value: "application/x-www-form-urlencoded;charset=UTF-8", description: "The format of the payload in the request body." });
  } else if (bodyMode === "binary") {
    list.push({ key: "Content-Type", value: "application/octet-stream", description: "The format of the payload in the request body." });
  }

  // 7. Content-Length
  if (bodyMode !== "none") {
    let len = "0";
    if (["json", "text", "javascript", "html", "xml"].includes(bodyMode)) {
      try {
        len = String(new TextEncoder().encode(bodyText || "").length);
      } catch {
        len = "<calculated when request is sent>";
      }
    } else {
      len = "<calculated when request is sent>";
    }
    list.push({ key: "Content-Length", value: len, description: "The size of the request body in bytes." });
  }

  // 8. Authorization
  if (auth.type === "bearer" && auth.token) {
    list.push({ key: "Authorization", value: `Bearer ${auth.token}`, description: "Used to provide credentials that authenticate a user agent with a server." });
  } else if (auth.type === "basic") {
    const creds = `${auth.username || ""}:${auth.password || ""}`;
    try {
      const encoded = btoa(creds);
      list.push({ key: "Authorization", value: `Basic ${encoded}`, description: "Used to provide credentials that authenticate a user agent with a server." });
    } catch {
      list.push({ key: "Authorization", value: `Basic <calculated>`, description: "Used to provide credentials that authenticate a user agent with a server." });
    }
  } else if (auth.type === "apiKey" && auth.in === "header" && auth.key) {
    list.push({ key: auth.key, value: auth.value || "", description: "API Key authorization header." });
  }

  return list;
};

const defaultAuth: ApiAuth = { type: "none" };

const safeParseJson = (
  text: string,
): { ok: true; value: any } | { ok: false } => {
  try {
    return { ok: true, value: JSON.parse(text) };
  } catch {
    return { ok: false };
  }
};

function findBreadcrumbPath(
  nodes: any[],
  targetId?: string,
  targetPath?: string,
  currentPath: string[] = []
): string[] | null {
  if (!nodes || !Array.isArray(nodes)) return null;
  for (const node of nodes) {
    if (!node) continue;
    const isRouteNode = node.method !== undefined;
    if (isRouteNode) {
      if (
        (targetId && node.id === targetId) ||
        (targetPath && targetPath !== "" && node.path === targetPath)
      ) {
        return [...currentPath, node.name];
      }
    } else {
      if (targetId && node.id === targetId) {
        return [...currentPath, node.name];
      }
      const found = findBreadcrumbPath(
        node.children || [],
        targetId,
        targetPath,
        [...currentPath, node.name]
      );
      if (found) return found;
    }
  }
  return null;
}

